#!/usr/bin/env python3
"""Offline checks for scripts/gen_tool_docs.py."""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / "scripts" / "gen_tool_docs.py"

CATALOG = [
    {
        "name": "bash",
        "description": "Run a shell command.\nSecond line.",
        "parameters": {
            "type": "object",
            "properties": {
                "command": {"type": "string", "description": "What to run | quoted"},
                "background": {"type": "boolean", "description": "Detach"},
                "mode": {"enum": ["fast", "slow"]},
                "files": {"type": "array", "items": {"type": "string"}},
            },
            "required": ["command"],
        },
        "profile": "core",
        "aliasOf": None,
        "guide": "Long notes here.",
    },
    {
        "name": "shell",
        "description": "Run a shell command.\nSecond line.",
        "parameters": {"type": "object", "properties": {}},
        "profile": "deferred",
        "aliasOf": "bash",
        "guide": None,
    },
    {
        "name": "noop",
        "description": "Does nothing.",
        "parameters": {"type": "object"},
        "profile": "deferred",
        "aliasOf": None,
        "guide": None,
    },
]


def run(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(GEN), *args], text=True, capture_output=True
    )


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)
        catalog = tmp_path / "catalog.json"
        out = tmp_path / "tools"
        catalog.write_text(json.dumps(CATALOG), encoding="utf-8")
        common = ["--catalog", str(catalog), "--out", str(out)]

        # --check before generation reports missing pages.
        r = run(*common, "--check")
        assert r.returncode == 1, r
        assert "missing:" in r.stdout, r.stdout

        r = run(*common)
        assert r.returncode == 0, r
        names = sorted(p.name for p in out.glob("*.md"))
        assert names == ["README.md", "bash.md", "noop.md"], names

        bash = (out / "bash.md").read_text(encoding="utf-8")
        assert bash.startswith("<!-- Generated by scripts/gen_tool_docs.py"), bash[:80]
        assert "# `bash`" in bash
        assert "Aliases: `shell`" in bash
        assert "Permission key: `[permission] bash`" in bash
        assert "| `command` | string | yes | What to run \\| quoted |" in bash, bash
        assert "| `background` | boolean | no | Detach |" in bash
        assert "| `files` | array of string | no |  |" in bash
        assert "| `mode` | one of `fast`, `slow` | no |  |" in bash
        assert "## Guide" in bash and "Long notes here." in bash
        assert "read agent://tools/bash" in bash
        assert "Deferred tools" not in bash

        noop = (out / "noop.md").read_text(encoding="utf-8")
        assert "This tool takes no parameters." in noop
        assert "## Guide" not in noop
        assert "Deferred tools are not advertised" in noop

        index = (out / "README.md").read_text(encoding="utf-8")
        assert "| [`bash`](bash.md) | core | Run a shell command. |" in index, index
        assert "| `shell` | alias | Same as [`bash`](bash.md). |" in index
        assert "| [`noop`](noop.md) | deferred | Does nothing. |" in index

        r = run(*common, "--check")
        assert r.returncode == 0, r
        assert "OK: 2 tool pages" in r.stdout, r.stdout

        # A hand edit is stale; an extra page is an orphan.
        (out / "noop.md").write_text(noop + "\nedited\n", encoding="utf-8")
        (out / "ghost.md").write_text("# ghost\n", encoding="utf-8")
        r = run(*common, "--check")
        assert r.returncode == 1, r
        assert "stale:" in r.stdout and "orphan" in r.stdout, r.stdout

        # Regenerating repairs the page and removes the orphan.
        r = run(*common)
        assert r.returncode == 0 and "removed 1 stale" in r.stdout, r
        assert not (out / "ghost.md").exists()
        assert run(*common, "--check").returncode == 0

        # An empty catalog is rejected.
        catalog.write_text("[]", encoding="utf-8")
        r = run(*common)
        assert r.returncode != 0 and "non-empty" in r.stderr, r

    # The committed pages must match the committed catalog.
    r = run("--check")
    assert r.returncode == 0, r.stdout + r.stderr
    print("ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
