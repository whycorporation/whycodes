#!/usr/bin/env python3
"""Render docs/tools/*.md from the committed tool catalog.

Source of truth: ``docs/tools/catalog.json``, written by
``whycodes debug --tools --json``. Each non-alias tool gets one page with its
description, parameter table, profile, permission key and long guide;
``docs/tools/README.md`` is the index.

    python scripts/gen_tool_docs.py            # (re)write the pages
    python scripts/gen_tool_docs.py --check    # exit 1 when a page is stale

Regenerate after changing a tool's name, description, schema, profile or
guide in Rust, from a binary built with ``--features ast-tools`` (the
catalog includes ``ast_grep`` / ``ast_edit``; the CLI test drops them in a
default build):

    whycodes debug --tools --json > docs/tools/catalog.json
    python scripts/gen_tool_docs.py

A CLI test (``committed_tool_catalog_matches_binary``) pins the committed
catalog to the binary; ``--check`` in CI pins the pages to the catalog.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CATALOG = ROOT / "docs" / "tools" / "catalog.json"
DEFAULT_OUT = ROOT / "docs" / "tools"
INDEX_NAME = "README.md"

BANNER = (
    "<!-- Generated by scripts/gen_tool_docs.py from docs/tools/catalog.json. "
    "Do not edit by hand: change the tool in Rust, run "
    "`whycodes debug --tools --json > docs/tools/catalog.json`, then "
    "`python scripts/gen_tool_docs.py`. -->"
)


def _cell(text: str) -> str:
    """One markdown table cell: no pipes, no newlines."""
    return " ".join(str(text).replace("|", "\\|").split())


def schema_type(schema: dict) -> str:
    """Human type for a JSON-schema property."""
    if "enum" in schema:
        return "one of " + ", ".join(f"`{v}`" for v in schema["enum"])
    kind = schema.get("type")
    if isinstance(kind, list):
        kind = " / ".join(str(k) for k in kind)
    if kind == "array":
        items = schema.get("items")
        inner = schema_type(items) if isinstance(items, dict) else "any"
        return f"array of {inner}"
    if "oneOf" in schema or "anyOf" in schema:
        variants = schema.get("oneOf") or schema.get("anyOf")
        return " or ".join(schema_type(v) for v in variants if isinstance(v, dict))
    return str(kind) if kind else "any"


def parameter_rows(parameters: dict) -> list[tuple[str, str, str, str]]:
    props = parameters.get("properties") or {}
    required = set(parameters.get("required") or [])
    rows = []
    for name in sorted(props):
        schema = props[name] if isinstance(props[name], dict) else {}
        rows.append(
            (
                f"`{name}`",
                schema_type(schema),
                "yes" if name in required else "no",
                _cell(schema.get("description", "")),
            )
        )
    return rows


def render_page(entry: dict, aliases: list[str]) -> str:
    name = entry["name"]
    lines = [BANNER, f"# `{name}`", ""]
    meta = [f"Profile: {entry['profile']}", f"Permission key: `[permission] {name}`"]
    if aliases:
        meta.append("Aliases: " + ", ".join(f"`{a}`" for a in sorted(aliases)))
    lines.append("> " + " · ".join(meta))
    lines.append("")
    lines.append(entry["description"].strip())
    lines.append("")
    if entry["profile"] == "deferred":
        lines.append(
            "Deferred tools are not advertised on every request. Activate one with "
            "`tool_search` or set `session.tool_profile = \"full\"`."
        )
        lines.append("")
    lines.append("## Parameters")
    lines.append("")
    rows = parameter_rows(entry.get("parameters") or {})
    if rows:
        lines.append("| Name | Type | Required | Description |")
        lines.append("|---|---|---|---|")
        for row in rows:
            lines.append("| " + " | ".join(row) + " |")
    else:
        lines.append("This tool takes no parameters.")
    lines.append("")
    if entry.get("guide"):
        lines.append("## Guide")
        lines.append("")
        lines.append(
            f"The model reads this with `read agent://tools/{name}`."
        )
        lines.append("")
        lines.append(entry["guide"].strip())
        lines.append("")
    lines.append("## Related")
    lines.append("")
    lines.append("- [User guide: Tools](../guide.md#tools)")
    lines.append("- [Permission gate](../internals/permission-gate.md)")
    lines.append("- [All tools](README.md)")
    return "\n".join(lines) + "\n"


def render_index(catalog: list[dict]) -> str:
    lines = [
        BANNER,
        "# Built-in tools",
        "",
        "One page per built-in tool, generated from the live catalog "
        "(`whycodes debug --tools --json`). MCP and plugin tools are per-install "
        "and not listed; see [the user guide](../guide.md#tools).",
        "",
        "`core` tools are advertised on every request. `deferred` tools need "
        "`tool_search` or `session.tool_profile = \"full\"`.",
        "",
        "| Tool | Profile | Description |",
        "|---|---|---|",
    ]
    for entry in catalog:
        name = entry["name"]
        if entry.get("aliasOf"):
            lines.append(
                f"| `{name}` | alias | Same as [`{entry['aliasOf']}`]({entry['aliasOf']}.md). |"
            )
            continue
        first = entry["description"].strip().splitlines()[0] if entry["description"].strip() else ""
        lines.append(f"| [`{name}`]({name}.md) | {entry['profile']} | {_cell(first)} |")
    lines.append("")
    lines.append("## Regenerating")
    lines.append("")
    lines.append("```bash")
    lines.append("whycodes debug --tools --json > docs/tools/catalog.json")
    lines.append("python scripts/gen_tool_docs.py")
    lines.append("python scripts/gen_tool_docs.py --check   # CI")
    lines.append("```")
    return "\n".join(lines) + "\n"


def render_all(catalog: list[dict]) -> dict[str, str]:
    """Map of file name → content for every page plus the index."""
    catalog = sorted(catalog, key=lambda e: e["name"])
    aliases: dict[str, list[str]] = {}
    for entry in catalog:
        primary = entry.get("aliasOf")
        if primary:
            aliases.setdefault(primary, []).append(entry["name"])
    pages = {INDEX_NAME: render_index(catalog)}
    for entry in catalog:
        if entry.get("aliasOf"):
            continue
        pages[f"{entry['name']}.md"] = render_page(entry, aliases.get(entry["name"], []))
    return pages


def load_catalog(path: Path) -> list[dict]:
    catalog = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(catalog, list) or not catalog:
        raise SystemExit(f"{path}: expected a non-empty JSON array")
    return catalog


def write_pages(out: Path, pages: dict[str, str]) -> int:
    out.mkdir(parents=True, exist_ok=True)
    for name, content in pages.items():
        (out / name).write_text(content, encoding="utf-8", newline="\n")
    stale = 0
    for existing in out.glob("*.md"):
        if existing.name not in pages:
            existing.unlink()
            stale += 1
    return stale


def check_pages(out: Path, pages: dict[str, str]) -> list[str]:
    problems = []
    for name, content in pages.items():
        path = out / name
        if not path.exists():
            problems.append(f"missing: {path}")
        elif path.read_text(encoding="utf-8") != content:
            problems.append(f"stale: {path}")
    for existing in sorted(out.glob("*.md")):
        if existing.name not in pages:
            problems.append(f"orphan (no catalog entry): {existing}")
    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--catalog", type=Path, default=DEFAULT_CATALOG)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="verify instead of write")
    args = ap.parse_args(argv)

    pages = render_all(load_catalog(args.catalog))
    if args.check:
        problems = check_pages(args.out, pages)
        for p in problems:
            print(p)
        if problems:
            print("docs/tools is out of date: run `python scripts/gen_tool_docs.py`")
            return 1
        print(f"OK: {len(pages) - 1} tool pages match {args.catalog.name}")
        return 0
    stale = write_pages(args.out, pages)
    print(f"wrote {len(pages) - 1} tool pages + index to {args.out}" + (f", removed {stale} stale" if stale else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
